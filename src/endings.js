
export function getEnding({ correct, errors, sanity }) {
  if (sanity <= 0 || errors >= 5) {
    return {
      title: "ФИНАЛ: СОТРУДНИК №14",
      text: "Твоё имя исчезло из документов. Утром на твоём месте сидел другой человек."
    };
  }

  if (correct >= 5 && errors <= 1) {
    return {
      title: "ФИНАЛ: ПОСЛЕДНИЙ ОТЧЁТ",
      text: "Ты замечал изменения и сообщал о них. На выходе ты видишь, что в журнале уже записана следующая смена."
    };
  }

  return {
    title: "ФИНАЛ: СМЕНА ЗАКРЫТА",
    text: "Ты покидаешь офис. В лифте слышишь звонок телефона из комнаты, в которой никого не осталось."
  };
}